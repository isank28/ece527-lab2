#!/usr/bin/env python3
"""
parse_reports.py — ECE 527 Project 2

Parse Design Compiler reports generated by the Task C and Task D scripts and
produce a comparison table:

    Task C: Array Multiplier vs Wallace Tree Multiplier
    Task D: Booth-2 Multiplier vs Task C Array Multiplier

Metrics extracted:
    - Total cells     (from *_qor.rpt or *_area.rpt)
    - Cell area       (from *_qor.rpt or *_area.rpt)
    - Max delay       (from *_timing.rpt — worst data arrival time)
    - Dynamic power   (from *_power.rpt)

Usage:
    cd /Users/victor/ece527/lab2
    python3 parse_reports.py                 # parse both TaskC and TaskD
    python3 parse_reports.py --task c        # Task C only
    python3 parse_reports.py --task d        # Task D only
    python3 parse_reports.py --format md     # emit markdown table

Requires only Python 3 standard library.
"""

import argparse
import re
import sys
from pathlib import Path
from typing import Optional, Tuple

LAB_ROOT = Path(__file__).resolve().parent
TASKC = LAB_ROOT / "TaskC"
TASKD = LAB_ROOT / "TaskD"

NA = "N/A"


def _first_number(text: str) -> Optional[float]:
    """Return the first float-like number found in *text*."""
    m = re.search(r"[-+]?\d*\.\d+|\d+", text)
    return float(m.group(0)) if m else None


def parse_qor(path: Path) -> Tuple[Optional[int], Optional[float]]:
    """
    Extract (number_of_cells, total_cell_area) from a DC QoR or area report.

    Looks for lines such as:
        Number of cells:                       123
        Total cell area:                    456.78 um^2
    """
    cells = None
    area = None
    try:
        text = path.read_text(errors="ignore")
    except FileNotFoundError:
        return cells, area

    for line in text.splitlines():
        low = line.lower()
        if "number of cells" in low and cells is None:
            cells = _first_number(line)
        if ("total cell area" in low or "cell area" in low) and area is None:
            val = _first_number(line)
            if val is not None:
                area = val

    return (int(cells) if cells is not None else None, area)


def parse_timing(path: Path) -> Optional[float]:
    """
    Extract the worst-case max delay (data arrival time) from a timing report.

    DC timing reports contain lines such as:
        Data arrival time:                  12.34 ns
    We take the maximum data-arrival value found.
    """
    best: Optional[float] = None
    try:
        text = path.read_text(errors="ignore")
    except FileNotFoundError:
        return best

    for line in text.splitlines():
        if "data arrival time" in line.lower():
            val = _first_number(line)
            if val is not None and (best is None or val > best):
                best = val

    return best


def parse_power(path: Path) -> Optional[float]:
    """
    Extract dynamic power from a power report.

    Looks for lines such as:
        Total Dynamic Power :               1.23 mW
        total dynamic power                 1.23 mW
    """
    power = None
    try:
        text = path.read_text(errors="ignore")
    except FileNotFoundError:
        return power

    for line in text.splitlines():
        low = line.lower()
        if "total dynamic power" in low:
            val = _first_number(line)
            if val is not None:
                power = val
                break  # take the first (summary) line

    return power


def collect(task_dir: Path, prefix: str) -> dict:
    """
    Collect all four metrics for one synthesized design.

    prefix is "array", "wallace", or "booth".
    """
    r = task_dir / "reports"
    cells, area = parse_qor(r / f"{prefix}_qor.rpt")
    # Fall back to area report if qor missing/incomplete
    if cells is None or area is None:
        c2, a2 = parse_qor(r / f"{prefix}_area.rpt")
        cells = cells if cells is not None else c2
        area = area if area is not None else a2
    delay = parse_timing(r / f"{prefix}_timing.rpt")
    power = parse_power(r / f"{prefix}_power.rpt")

    return {
        "prefix": prefix,
        "cells": cells if cells is not None else NA,
        "area": f"{area:.3f}" if isinstance(area, (int, float)) else NA,
        "delay": f"{delay:.3f} ns" if isinstance(delay, (int, float)) else NA,
        "power": f"{power:.3f} mW" if isinstance(power, (int, float)) else NA,
    }


def print_table(rows: list[dict], title: str, fmt: str = "grid") -> None:
    """Print a simple text table (no external dependencies)."""
    print("\n" + "=" * 60)
    print(title)
    print("=" * 60)

    headers = ["Metric"] + [r["prefix"].replace("_", " ").title() for r in rows]
    metrics = ["cells", "area", "delay", "power"]
    metric_labels = {
        "cells": "Total cells",
        "area": "Cell area",
        "delay": "Max delay",
        "power": "Dynamic power",
    }

    # Column widths
    widths = [max(len(h), len(metric_labels[m])) for h, m in zip(headers, [None] * 0)]
    # recompute properly
    col_widths = [len(headers[0])]
    for h in headers[1:]:
        col_widths.append(len(h))
    for m in metrics:
        col_widths[0] = max(col_widths[0], len(metric_labels[m]))

    def fmt_row(vals):
        return " | ".join(v.ljust(w) for v, w in zip(vals, col_widths))

    print(fmt_row(headers))
    print("-+-".join("-" * w for w in col_widths))
    for m in metrics:
        row = [metric_labels[m]] + [r[m] for r in rows]
        print(fmt_row(row))
    print()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Parse DC reports and generate a comparison table."
    )
    parser.add_argument(
        "--task",
        choices=["c", "d", "both"],
        default="both",
        help="Which task(s) to parse (default: both).",
    )
    parser.add_argument(
        "--format",
        choices=["text", "md"],
        default="text",
        help="Output format (default: text).",
    )
    args = parser.parse_args()

    if args.task in ("c", "both"):
        array_missing = not (TASKC / "reports" / "array_qor.rpt").exists()
        wallace_missing = not (TASKC / "reports" / "wallace_qor.rpt").exists()
        if array_missing or wallace_missing:
            print(
                "NOTE: Task C DC reports not found yet. Run ./run_dc.sh in TaskC first.\n"
                "      Showing placeholder table.",
                file=sys.stderr,
            )
        rows = [
            collect(TASKC, "array"),
            collect(TASKC, "wallace"),
        ]
        print_table(
            rows,
            "Task C — 8×8 Multiplier Comparison (Array vs Wallace)",
            fmt=args.format,
        )

    if args.task in ("d", "both"):
        booth_missing = not (TASKD / "reports" / "booth_qor.rpt").exists()
        if booth_missing:
            print(
                "NOTE: Task D DC report not found yet. Run ./run_dc.sh in TaskD first.\n"
                "      Showing placeholder table.",
                file=sys.stderr,
            )
        rows = [collect(TASKD, "booth")]
        print_table(
            rows,
            "Task D — Booth-2 Multiplier",
            fmt=args.format,
        )

    if args.task in ("c", "both"):
        # Side-by-side Task C array vs Task D booth (Task D asks for this comparison)
        array = collect(TASKC, "array")
        booth = collect(TASKD, "booth")
        rows = [array, booth]
        print_table(
            rows,
            "Task D Comparison — Array Multiplier (Task C) vs Booth-2 (Task D)",
            fmt=args.format,
        )

    return 0


if __name__ == "__main__":
    sys.exit(main())
